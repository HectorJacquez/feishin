"""Generate Feishin themes from the homelab palettes Tempo carries.

The palettes originate on the work-server (Tempo imports them with
tools/import_symfonium_theme.py into themes_custom.xml), so this is the same
set of colours across the site, the phone and now the desktop. Run after the
Tempo side regenerates:

    python tools/import-tempo-themes.py

Writes src/shared/themes/hedgy-<slug>/hedgy-<slug>.ts, one per palette, and
prints the registry lines to paste into app-theme-types.ts, app-theme.ts and
use-app-theme.ts (idempotent: it patches those three files itself when the
markers are present).
"""
import os
import re
import xml.etree.ElementTree as ET

TEMPO_XML = r'C:\dev\tempo\app\src\main\res\values\themes_custom.xml'
TEMPO_ARRAYS = r'C:\dev\tempo\app\src\main\res\values\arrays_themes.xml'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
THEMES_DIR = os.path.join(ROOT, 'src', 'shared', 'themes')


def rgb(hex_colour):
    h = hex_colour.lstrip('#')
    if len(h) == 8:  # #AARRGGBB
        h = h[2:]
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    return r, g, b


def css_rgb(hex_colour):
    return 'rgb(%d, %d, %d)' % rgb(hex_colour)


def luminance(hex_colour):
    r, g, b = rgb(hex_colour)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def camel(slug):
    parts = slug.split('-')
    return parts[0] + ''.join(p.capitalize() for p in parts[1:])


def const_name(slug):
    return slug.replace('-', '_').upper()


def load_labels():
    tree = ET.parse(TEMPO_ARRAYS)
    entries = values = []
    for arr in tree.getroot().findall('string-array'):
        items = [i.text for i in arr.findall('item')]
        if arr.get('name') == 'custom_theme_entries':
            entries = items
        elif arr.get('name') == 'custom_theme_values':
            values = items
    return dict(zip(values, entries))


def load_palettes():
    tree = ET.parse(TEMPO_XML)
    palettes = {}
    for style in tree.getroot().findall('style'):
        name = style.get('name')  # AppTheme.server_aero_sky
        if not name.startswith('AppTheme.server_'):
            continue
        key = 'server-' + name[len('AppTheme.server_'):].replace('_', '-')
        palettes[key] = {item.get('name'): item.text for item in style.findall('item')}
    return palettes


def theme_ts(slug, label, p):
    bg = p['android:colorBackground']
    r, g, b = rgb(bg)
    mode = 'light' if luminance(bg) > 140 else 'dark'
    primary = p['colorPrimary']
    pr, pg, pb = rgb(primary)
    return f'''import {{ AppThemeConfiguration }} from '/@/shared/themes/app-theme-types';

// {label}: one of the homelab palettes, generated by tools/import-tempo-themes.py
// from Tempo's themes_custom.xml. Do not hand-edit; re-run the script.
export const {camel(slug)}: AppThemeConfiguration = {{
    app: {{
        'overlay-header':
            'linear-gradient(transparent 0%, rgb({r} {g} {b} / 85%) 100%), var(--theme-background-noise)',
        'overlay-subheader':
            'linear-gradient(180deg, rgb({r} {g} {b} / 5%) 0%, var(--theme-colors-background) 100%), var(--theme-background-noise)',
        'scrollbar-handle-background': 'rgba({pr}, {pg}, {pb}, 20%)',
        'scrollbar-handle-hover-background': 'rgba({pr}, {pg}, {pb}, 40%)',
    }},
    colors: {{
        background: '{css_rgb(bg)}',
        'background-alternate': '{css_rgb(p['colorSurfaceContainerLow'])}',
        black: 'rgb(0, 0, 0)',
        foreground: '{css_rgb(p['colorOnBackground'])}',
        'foreground-muted': '{css_rgb(p['colorOnSurfaceVariant'])}',
        primary: '{css_rgb(primary)}',
        'state-error': '{css_rgb(p['colorError'])}',
        'state-info': '{css_rgb(p['colorTertiary'])}',
        'state-success': '{css_rgb(p['colorRoleG'])}',
        'state-warning': '{css_rgb(p['colorRoleW'])}',
        surface: '{css_rgb(p['colorSurfaceContainer'])}',
        'surface-foreground': '{css_rgb(p['colorOnSurface'])}',
        white: 'rgb(255, 255, 255)',
    }},
    mode: '{mode}',
}};
'''


def write(path, text):
    with open(path, 'wb') as f:
        f.write(text.encode('utf-8'))


def patch_between(path, start, end, body):
    """Replace everything between two marker comments (kept), or fail loudly."""
    s = open(path, 'rb').read().decode('utf-8')
    i, j = s.index(start) + len(start), s.index(end)
    s = s[:i] + '\n' + body + s[j:]
    write(path, s)


def main():
    labels = load_labels()
    palettes = load_palettes()
    entries = []
    for key, p in sorted(palettes.items()):
        slug = 'hedgy-' + key[len('server-'):]
        label = labels.get(key, slug)
        d = os.path.join(THEMES_DIR, slug)
        os.makedirs(d, exist_ok=True)
        write(os.path.join(d, slug + '.ts'), theme_ts(slug, label, p))
        mode = 'light' if luminance(p['android:colorBackground']) > 140 else 'dark'
        entries.append((slug, camel(slug), const_name(slug), 'Hedgy ' + label, mode))
        print('wrote', slug, mode)

    # registry: enum members, theme map entries, picker entries
    patch_between(os.path.join(THEMES_DIR, 'app-theme-types.ts'),
                  '    // hedgy-themes:start', '    // hedgy-themes:end',
                  ''.join(f"    {c} = '{cm}',\n" for _, cm, c, _, _ in entries))
    patch_between(os.path.join(THEMES_DIR, 'app-theme.ts'),
                  '// hedgy-themes:imports:start', '// hedgy-themes:imports:end',
                  ''.join(f"import {{ {cm} }} from '/@/shared/themes/{s}/{s}';\n" for s, cm, _, _, _ in entries))
    patch_between(os.path.join(THEMES_DIR, 'app-theme.ts'),
                  '    // hedgy-themes:map:start', '    // hedgy-themes:map:end',
                  ''.join(f"    [AppTheme.{c}]: {cm},\n" for _, cm, c, _, _ in entries))
    patch_between(os.path.join(ROOT, 'src', 'renderer', 'themes', 'use-app-theme.ts'),
                  '    // hedgy-themes:start', '    // hedgy-themes:end',
                  ''.join(f"    {{ label: '{lab}', type: '{m}', value: AppTheme.{c} }},\n" for _, _, c, lab, m in entries))
    print('registered', len(entries), 'themes')


if __name__ == '__main__':
    main()
